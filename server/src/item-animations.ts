/**
 * The states an item can actually be put into.
 *
 * ── Why this exists ─────────────────────────────────────────────────────────
 * `furni-footprint.statesFor()` counts the trailing field of furnimap sprite
 * names. That is right for items whose states are drawn as furnimap sprites —
 * the Haunted Mansion candlestick has `..._0` and `..._1`, so it counts 2 and
 * its on/off toggle works. But an item may instead keep its states in its
 * `item.<code>.ani.xml` structure, and the furnimap then shows only state 0:
 *
 *   118 candlestick   furnimap [0,1]   ani —          -> 2   worked
 *   38  RNG           furnimap [0]     ani [0..6,10]  -> 1   dead
 *   40  scoreboard    furnimap [0]     ani [1..5]     -> 1   dead
 *   41  turnstile     furnimap [0]     ani [1]        -> 1   dead
 *
 * The room-item handler refuses anything reporting a single state, so those
 * three were rejected before it did any work. That — not `the doubleClick`, and
 * not a missing `UseItem` — is why they felt inert while the lights worked.
 *
 * ⚠ Two consequences for the cycling rule:
 *
 *   • States are NOT `0..n-1`. The scoreboard has no state 0 in its ANI, and
 *     the RNG skips 7/8/9 to reach 10. `(state + 1) % count` would land on
 *     states with no artwork, so we step through the ACTUAL list instead.
 *   • The two sources are additive, not alternatives. The turnstile's ANI
 *     defines only the turn (state 1); its resting closed pose is the furnimap
 *     sprite (state 0). Taking the union is what makes it the open/close pair
 *     it visibly is.
 *
 * Generated by `tools/extract-item-animations.mjs`, which reads Disney's own
 * structures out of the casts and resolves `memberalias.index` borrowings
 * (126 -> 41, and 34 others).
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spriteStatesFor } from "./furni-footprint.js";

const here = dirname(fileURLToPath(import.meta.url));

interface AniState {
  state: number;
  dirs: number[];
  frames: number;
  loop: number;
}

interface AniItem {
  states: AniState[];
  delay?: number;
  interactive?: number;
  name: string;
  aliasOf?: number;
}

const ani = new Map<number, AniItem>();
/** typeCode -> every state the item can be drawn in, ascending. */
const effective = new Map<number, number[]>();
let loaded = false;

function load(): void {
  if (loaded) return;
  loaded = true;
  const path =
    process.env.VMK_ITEM_ANIMATIONS ?? join(here, "..", "..", "assets", "item-animations.json");
  if (!existsSync(path)) {
    console.log(`[ani] no animation data at ${path} — interactive items limited to furnimap states`);
    return;
  }
  const data = JSON.parse(readFileSync(path, "utf8")) as { items: Record<string, AniItem> };
  for (const [code, item] of Object.entries(data.items)) ani.set(Number(code), item);
  const multi = [...ani.values()].filter((i) => i.states.length > 1).length;
  console.log(`[ani] ${ani.size} items with animation, ${multi} with more than one state`);
}

/**
 * Every state this item can be put into at `dir`, ascending.
 *
 * The union of its furnimap sprite states and its animation states — see the
 * note above on why neither source alone is sufficient.
 *
 * ⚠ Facing matters, and omitting it puts items into states that draw NOTHING.
 * An ANI names the facings each state has art for, and they are often a subset:
 * the scoreboard and the RNG define only dirs 3 and 5, so at dir 1 or 7 their
 * animated states do not exist. The furnimap's own states stay available at
 * every facing, because the furnimap defines all four.
 *
 * Pass no `dir` for the item's full repertoire regardless of facing.
 */
export function statesOf(typeCode: number, dir?: number): number[] {
  load();
  const key = dir === undefined ? typeCode : typeCode * 10 + dir;
  const cached = effective.get(key);
  if (cached) return cached;
  const all = new Set<number>(spriteStatesFor(typeCode));
  for (const s of ani.get(typeCode)?.states ?? []) {
    if (dir === undefined || s.dirs.length === 0 || s.dirs.includes(dir)) all.add(s.state);
  }
  // Every item rests in state 0, even when neither source names it: that is
  // the state it is placed in and the one the DB defaults to.
  all.add(0);
  const list = [...all].sort((a, b) => a - b);
  effective.set(key, list);
  return list;
}

/** The state that follows `current` at this facing, wrapping. */
export function nextStateOf(typeCode: number, current: number, dir?: number): number {
  const list = statesOf(typeCode, dir);
  if (list.length <= 1) return current;
  const at = list.indexOf(current);
  // An unknown current state (hand-set, or the item rotated out of the facing
  // that state had art for) restarts the cycle rather than sticking.
  return at < 0 ? list[0] : list[(at + 1) % list.length];
}

/**
 * The facings this item has animation art for, or empty if it animates at any.
 *
 * ⚠ Not the same as the furnimap's facings. The scoreboard has furnimap art for
 * all of 1/3/5/7 but animates only at 3 and 5.
 */
export function animatedDirsOf(typeCode: number): number[] {
  load();
  const dirs = new Set<number>();
  for (const s of ani.get(typeCode)?.states ?? []) for (const d of s.dirs) dirs.add(d);
  return [...dirs].sort((a, b) => a - b);
}

/**
 * The state an item plays THROUGH rather than settles in, or null.
 *
 * The RNG is the case this exists for. Its states 0-6 are seven results of two
 * frames each; state 10 is a fourteen-frame roll, numbered past a 7/8/9 gap
 * precisely because it is not one of the results. So a state several times
 * longer than its siblings is the animation and the rest are outcomes.
 *
 * ⚠ Detect the roll itself rather than inferring one from "the results are a
 * subset of the states". `statesOf` adds furnimap state 0 to every item, which
 * would make that subset test true for the scoreboard too — and the scoreboard
 * has no roll, just five equal light settings to step through in order.
 */
export function rollStateOf(typeCode: number): number | null {
  load();
  const states = ani.get(typeCode)?.states ?? [];
  if (states.length < 3) return null;
  const frames = states.map((s) => s.frames).sort((a, b) => a - b);
  const median = frames[Math.floor(frames.length / 2)];
  const long = states.filter((s) => s.frames > median * 2);
  // Two or more "long" states means the frame counts are merely uneven, not
  // that one of them is an animation the others are outcomes of.
  return long.length === 1 ? long[0].state : null;
}

/** The states this item settles on at `dir`: everything except its roll. */
export function resultStatesOf(typeCode: number, dir?: number): number[] {
  const roll = rollStateOf(typeCode);
  const all = statesOf(typeCode, dir);
  if (roll === null) return all;
  const results = all.filter((s) => s !== roll);
  return results.length > 0 ? results : all;
}

/**
 * How long this item's roll takes to play, in milliseconds.
 *
 * `DELAY` is ticks between frames and Director's tick is 1/60s, so the run is
 * `framesPerDir * delay / 60`. The RNG's roll is seven frames at DELAY="4",
 * about 470ms — it plays its seven results in order, which is exactly what a
 * spin looks like.
 *
 * ⚠ `frames` counts every FRAME in the state, across ALL its facings, so it
 * must be divided by the number of facings to get the length actually played.
 * Using the raw count would double the wait for a two-facing item.
 */
export function rollDurationMs(typeCode: number): number {
  load();
  const item = ani.get(typeCode);
  const roll = rollStateOf(typeCode);
  if (!item || roll === null) return 0;
  const state = item.states.find((s) => s.state === roll);
  if (!state) return 0;
  const perDir = state.frames / Math.max(state.dirs.length, 1);
  return Math.round((perDir * (item.delay ?? 4) * 1000) / 60);
}

/**
 * How long one play of `state` lasts, or 0 if it loops until told to stop.
 *
 * `LOOP` is a COUNT: `CRoomItemStateAnimator` plays the state that many times
 * and then drops the item back to state 0 by itself (`loopsReached`). Its
 * `m_iDelay` counts `update` calls, i.e. movie FRAMES at 24 fps — not ticks — so
 * one pass is `framesPerDir * delay` frames. The Unbirthday Cake: 3 frames x
 * DELAY 5 x LOOP 6 = 90 frames = 3.75 s.
 */
export function playDurationMs(typeCode: number, state: number): number {
  load();
  const item = ani.get(typeCode);
  const entry = item?.states.find((s) => s.state === state);
  if (!item || !entry || !(entry.loop > 0)) return 0;
  const perDir = entry.frames / Math.max(entry.dirs.length, 1);
  return Math.round((perDir * (item.delay ?? 4) * entry.loop * 1000) / 24);
}

/** Does this item animate at all? */
export function hasAnimation(typeCode: number): boolean {
  load();
  return ani.has(typeCode);
}

/** The catalogue name recorded alongside the structure, for logging. */
export function animationNameOf(typeCode: number): string {
  load();
  return ani.get(typeCode)?.name ?? "";
}
